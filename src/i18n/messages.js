const TABLES = { en: EN, bn: BN };

export const LOCALE_KEY = 'bph_locale';

export function interpolate(str, vars = {}) {
  return String(str || '').replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
}

export function translate(locale, key, vars) {
  const table = TABLES[locale] || EN;
  const raw = table[key] || EN[key] || key;
  return vars ? interpolate(raw, vars) : raw;
}

/** Keys present in English but missing from Bengali — keep shopper chrome in sync. */
export function missingBengaliKeys() {
  return Object.keys(EN).filter((k) => !Object.prototype.hasOwnProperty.call(BN, k));
}

export function readLocale() {
  if (typeof window === 'undefined') return 'en';
  try {
    const v = localStorage.getItem(LOCALE_KEY);
    return v === 'bn' ? 'bn' : 'en';
  } catch {
    return 'en';
  }
}

export function writeLocale(locale) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LOCALE_KEY, locale === 'bn' ? 'bn' : 'en');
  } catch {
    /* ignore */
  }
}

